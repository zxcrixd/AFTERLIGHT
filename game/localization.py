def tr(language, key, **values):
    """Return a translated string, falling back to Russian and then the key."""
    table = STRINGS.get(language, STRINGS["ru"])
    text = table.get(key, STRINGS["ru"].get(key, key))

    if values:
        try:
            text = text.format(**values)
        except (KeyError, ValueError):
            pass

    return text
